import fs from 'node:fs';
import path from 'node:path';

const projectRoot = process.cwd();
const docsRoot = path.join(projectRoot, 'src', 'content', 'docs', 'docs');
const generatedDirectory = path.join(projectRoot, 'scripts', 'generated');
const outputFile = path.join(
	generatedDirectory,
	'sync-wiki-revisions.sql'
);

const SYSTEM_USER_ID =
	'00000000-0000-0000-0000-000000000001';

const SUPPORTED_EXTENSIONS = new Set(['.md', '.mdx']);

function getTitle(content, filePath) {
	const match = content.match(/^---\s*\n([\s\S]*?)\n---\s*(?:\n|$)/);

	if (!match) {
		throw new Error(`frontmatter がありません: ${filePath}`);
	}

	const frontmatter = match[1];

	const titleMatch = frontmatter.match(
		/^title\s*:\s*(?:"([^"]*)"|'([^']*)'|(.+))\s*$/m
	);

	if (!titleMatch) {
		throw new Error(`title がありません: ${filePath}`);
	}

	return (
		titleMatch[1] ??
		titleMatch[2] ??
		titleMatch[3]
	).trim();
}

function collectFiles(directory) {
	const results = [];

	for (const entry of fs.readdirSync(directory, {
		withFileTypes: true,
	})) {
		const fullPath = path.join(directory, entry.name);

		if (entry.isDirectory()) {
			results.push(...collectFiles(fullPath));
			continue;
		}

		if (!entry.isFile()) continue;

		if (
			!SUPPORTED_EXTENSIONS.has(
				path.extname(entry.name).toLowerCase()
			)
		) {
			continue;
		}

		results.push(fullPath);
	}

	return results;
}

function getPublicPath(filePath) {
	const relative = path.relative(docsRoot, filePath);
	const parsed = path.parse(relative);

	let urlPath;

	if (parsed.name === 'index') {
		const directory = parsed.dir.replaceAll(path.sep, '/');

		urlPath = directory
			? `/docs/${directory}/`
			: '/docs/';
	} else {
		const directory = parsed.dir.replaceAll(path.sep, '/');

		urlPath = directory
			? `/docs/${directory}/${parsed.name}/`
			: `/docs/${parsed.name}/`;
	}

	return urlPath.replace(/\/+/g, '/');
}

function getSourcePath(filePath) {
	return path
		.relative(projectRoot, filePath)
		.split(path.sep)
		.join('/');
}

function escapeSql(value) {
	return value.replaceAll("'", "''");
}

function createSql(pages) {
	const timestamp = new Date().toISOString();
	const lines = [];

	lines.push('-- ========================================================');
	lines.push('-- NUGBASE Wiki revisions initial synchronization');
	lines.push('-- Generated by scripts/sync-wiki-revisions.mjs');
	lines.push('-- ========================================================');
	lines.push(`-- Generated at: ${timestamp}`);
	lines.push(`-- Pages: ${pages.length}`);
	lines.push('--');
	lines.push('-- Initial revision number: 1');
	lines.push(`-- System editor: ${SYSTEM_USER_ID}`);
	lines.push('--');
	lines.push('-- This SQL creates the initial wiki_revisions rows');
	lines.push('-- and connects them to wiki_pages.published_revision_id.');
	lines.push('-- ========================================================');
	lines.push('');

	lines.push('BEGIN TRANSACTION;');
	lines.push('');

	for (const page of pages) {
		const revisionId = crypto.randomUUID();
		const content = escapeSql(page.content);

		lines.push(`-- ${page.path}`);
		lines.push(
			`INSERT INTO wiki_revisions (id, page_id, revision_number, content, editor_id, created_at)`
		);
		lines.push(
			`SELECT '${revisionId}', id, 1, '${content}', '${SYSTEM_USER_ID}', '${timestamp}'`
		);
		lines.push(
			`FROM wiki_pages`
		);
		lines.push(
			`WHERE source_path = '${escapeSql(page.sourcePath)}';`
		);
		lines.push('');

		lines.push(
			`UPDATE wiki_pages`
		);
		lines.push(
			`SET published_revision_id = '${revisionId}', updated_at = '${timestamp}'`
		);
		lines.push(
			`WHERE source_path = '${escapeSql(page.sourcePath)}';`
		);
		lines.push('');
	}

	lines.push('COMMIT;');
	lines.push('');

	return lines.join('\n');
}

function main() {
	const generateSql = process.argv.includes('--generate-sql');

	if (!fs.existsSync(docsRoot)) {
		throw new Error(
			`Wikiディレクトリが見つかりません:\n${docsRoot}`
		);
	}

	const files = collectFiles(docsRoot).sort();

	console.log('');
	console.log('========================================');
	console.log('NUGBASE Wiki Revision 同期 dry-run');
	console.log('========================================');
	console.log('');

	console.log(`対象ディレクトリ: ${docsRoot}`);
	console.log(`検出ファイル数: ${files.length}`);
	console.log('');

	const pages = [];
	const errors = [];

	for (const filePath of files) {
		try {
			const content = fs.readFileSync(filePath, 'utf8');

			const title = getTitle(content, filePath);
			const sourcePath = getSourcePath(filePath);
			const publicPath = getPublicPath(filePath);

			pages.push({
				title,
				path: publicPath,
				sourcePath,
				content,
			});
		} catch (error) {
			errors.push({
				filePath,
				message:
					error instanceof Error
						? error.message
						: String(error),
			});
		}
	}

	for (const page of pages) {
		console.log(`[OK] ${page.path}`);
		console.log(`     title: ${page.title}`);
		console.log(`     source: ${page.sourcePath}`);
		console.log(
			`     content: ${page.content.length} characters`
		);
		console.log('');
	}

	if (errors.length > 0) {
		console.log('========================================');
		console.log('エラー');
		console.log('========================================');
		console.log('');

		for (const error of errors) {
			console.log(`[ERROR] ${error.filePath}`);
			console.log(`        ${error.message}`);
			console.log('');
		}
	}

	console.log('========================================');
	console.log('結果');
	console.log('========================================');

	console.log(`検出: ${files.length} ファイル`);
	console.log(`成功: ${pages.length} ファイル`);
	console.log(`エラー: ${errors.length} ファイル`);
	console.log('');

	if (errors.length > 0) {
		console.log(
			'✗ エラーがあるため、SQLは生成しません。'
		);
		console.log('');

		process.exitCode = 1;
		return;
	}

	console.log(
		'✓ すべてのWikiページを正常に読み込めました。'
	);

	if (!generateSql) {
		console.log(
			'✓ SQL生成モードではないため、SQLファイルは作成しません。'
		);
		console.log('');
		return;
	}

	fs.mkdirSync(generatedDirectory, {
		recursive: true,
	});

	const sql = createSql(pages);

	fs.writeFileSync(
		outputFile,
		sql,
		'utf8'
	);

	console.log('');
	console.log('========================================');
	console.log('SQL生成');
	console.log('========================================');
	console.log('');

	console.log('✓ SQLファイルを生成しました。');
	console.log(`  ${outputFile}`);
	console.log('');

	console.log(
		`✓ ${pages.length}ページ分のRevision 1を生成しました。`
	);

	console.log(
		'✓ wiki_pages.published_revision_id の更新SQLも含まれています。'
	);

	console.log('✓ D1への書き込みはまだ行っていません。');
	console.log('');
}

main();