import fs from 'node:fs';
import path from 'node:path';

const projectRoot = process.cwd();

const docsRoot = path.join(
	projectRoot,
	'src',
	'content',
	'docs',
	'docs',
);

const generatedDirectory = path.join(
	projectRoot,
	'scripts',
	'generated',
);

const outputFile = path.join(
	generatedDirectory,
	'initialize-production-wiki.sql',
);

const SYSTEM_USER_ID =
	'00000000-0000-0000-0000-000000000001';

const SYSTEM_USER_NAME = 'NUGBASE';

const EXPECTED_PAGE_COUNT = 38;

const SUPPORTED_EXTENSIONS = new Set([
	'.md',
	'.mdx',
]);


/* =========================================================
   Frontmatter
   ========================================================= */

function getTitle(content, filePath) {
	const match = content.match(
		/^---\s*\n([\s\S]*?)\n---\s*(?:\n|$)/,
	);

	if (!match) {
		throw new Error(
			`frontmatter がありません: ${filePath}`,
		);
	}

	const frontmatter = match[1];

	const titleMatch = frontmatter.match(
		/^title\s*:\s*(?:"([^"]*)"|'([^']*)'|(.+))\s*$/m,
	);

	if (!titleMatch) {
		throw new Error(
			`title がありません: ${filePath}`,
		);
	}

	return (
		titleMatch[1] ??
		titleMatch[2] ??
		titleMatch[3]
	).trim();
}


/* =========================================================
   Wiki files
   ========================================================= */

function collectFiles(directory) {
	const results = [];

	for (const entry of fs.readdirSync(directory, {
		withFileTypes: true,
	})) {
		const fullPath = path.join(
			directory,
			entry.name,
		);

		if (entry.isDirectory()) {
			results.push(
				...collectFiles(fullPath),
			);

			continue;
		}

		if (!entry.isFile()) {
			continue;
		}

		if (
			!SUPPORTED_EXTENSIONS.has(
				path.extname(entry.name).toLowerCase(),
			)
		) {
			continue;
		}

		results.push(fullPath);
	}

	return results;
}


/* =========================================================
   Public URL
   ========================================================= */

function getPublicPath(filePath) {
	const relative = path.relative(
		docsRoot,
		filePath,
	);

	const parsed = path.parse(relative);

	let urlPath;

	if (parsed.name === 'index') {
		const directory =
			parsed.dir.replaceAll(
				path.sep,
				'/',
			);

		urlPath = directory
			? `/docs/${directory}/`
			: '/docs/';
	} else {
		const directory =
			parsed.dir.replaceAll(
				path.sep,
				'/',
			);

		urlPath = directory
			? `/docs/${directory}/${parsed.name}/`
			: `/docs/${parsed.name}/`;
	}

	return urlPath.replace(
		/\/+/g,
		'/',
	);
}


/* =========================================================
   Source path
   ========================================================= */

function getSourcePath(filePath) {
	return path
		.relative(
			projectRoot,
			filePath,
		)
		.split(path.sep)
		.join('/');
}


/* =========================================================
   SQL escaping
   ========================================================= */

function escapeSql(value) {
	return String(value).replaceAll(
		"'",
		"''",
	);
}


/* =========================================================
   SQL generation
   ---------------------------------------------------------
   IMPORTANT:
   Cloudflare D1 の `wrangler d1 execute --remote
   --file=...` では BEGIN TRANSACTION / COMMIT を
   SQLファイルに含めない。
   ========================================================= */

function createSql(pages) {
	const timestamp =
		new Date().toISOString();

	const lines = [];

	lines.push(
		'-- ========================================================',
	);

	lines.push(
		'-- NUGBASE Production Wiki Initializer',
	);

	lines.push(
		'-- Generated by scripts/initialize-production-wiki.mjs',
	);

	lines.push(
		'-- ========================================================',
	);

	lines.push(
		`-- Generated at: ${timestamp}`,
	);

	lines.push(
		`-- Wiki pages: ${pages.length}`,
	);

	lines.push('');

	lines.push(
		'-- IMPORTANT:',
	);

	lines.push(
		'-- This SQL is intended for the first initialization',
	);

	lines.push(
		'-- of an empty production D1 database.',
	);

	lines.push(
		'-- It does NOT create Google users.',
	);

	lines.push(
		'-- Google users are created automatically by OAuth login.',
	);

	lines.push(
		'-- Cloudflare D1 remote execution does not use',
	);

	lines.push(
		'-- BEGIN TRANSACTION or COMMIT in this SQL file.',
	);

	lines.push('');


	/* =====================================================
	   01. System user
	   ===================================================== */

	lines.push(
		'-- ======================================================',
	);

	lines.push(
		'-- 01. System user',
	);

	lines.push(
		'-- ======================================================',
	);

	lines.push('');

	lines.push(
		`INSERT INTO users (
	id,
	display_name,
	email,
	avatar_url,
	role,
	created_at,
	updated_at
)
VALUES (
	'${SYSTEM_USER_ID}',
	'${SYSTEM_USER_NAME}',
	NULL,
	NULL,
	'admin',
	'${timestamp}',
	'${timestamp}'
)
ON CONFLICT(id) DO NOTHING;`,
	);

	lines.push('');


	/* =====================================================
	   02. Wiki pages
	   ===================================================== */

	lines.push(
		'-- ======================================================',
	);

	lines.push(
		'-- 02. Wiki pages',
	);

	lines.push(
		'-- ======================================================',
	);

	lines.push('');

	for (const page of pages) {
		const pageId =
			crypto.randomUUID();

		lines.push(
			`-- ${page.path}`,
		);

		lines.push(
			`INSERT INTO wiki_pages (
	id,
	path,
	title,
	source_path,
	published_revision_id,
	created_at,
	updated_at
)
VALUES (
	'${pageId}',
	'${escapeSql(page.path)}',
	'${escapeSql(page.title)}',
	'${escapeSql(page.sourcePath)}',
	NULL,
	'${timestamp}',
	'${timestamp}'
)
ON CONFLICT(source_path) DO UPDATE SET
	path = excluded.path,
	title = excluded.title,
	updated_at = excluded.updated_at;`,
		);

		lines.push('');
	}


	/* =====================================================
	   03. Initial revisions
	   ===================================================== */

	lines.push(
		'-- ======================================================',
	);

	lines.push(
		'-- 03. Initial revisions',
	);

	lines.push(
		'-- ======================================================',
	);

	lines.push('');

	for (const page of pages) {
		const revisionId =
			crypto.randomUUID();

		const content =
			escapeSql(page.content);

		lines.push(
			`-- ${page.path}`,
		);

		/*
		 * Revision 1 is created only when the page has
		 * no published revision yet.
		 *
		 * This prevents accidental duplication if this
		 * generated SQL is executed again.
		 */

		lines.push(
			`INSERT INTO wiki_revisions (
	id,
	page_id,
	revision_number,
	content,
	editor_id,
	created_at
)
SELECT
	'${revisionId}',
	id,
	1,
	'${content}',
	'${SYSTEM_USER_ID}',
	'${timestamp}'
FROM wiki_pages
WHERE source_path = '${escapeSql(page.sourcePath)}'
  AND published_revision_id IS NULL
  AND NOT EXISTS (
	SELECT 1
	FROM wiki_revisions
	WHERE wiki_revisions.page_id = wiki_pages.id
);`,
		);

		lines.push('');

		lines.push(
			`UPDATE wiki_pages
SET
	published_revision_id = '${revisionId}',
	updated_at = '${timestamp}'
WHERE source_path = '${escapeSql(page.sourcePath)}'
  AND published_revision_id IS NULL
  AND EXISTS (
	SELECT 1
	FROM wiki_revisions
	WHERE wiki_revisions.id = '${revisionId}'
);`,
		);

		lines.push('');
	}


	/* =====================================================
	   04. Validation
	   ===================================================== */

	lines.push(
		'-- ======================================================',
	);

	lines.push(
		'-- 04. Validation',
	);

	lines.push(
		'-- ======================================================',
	);

	lines.push('');

	lines.push(
		`SELECT
	'users' AS table_name,
	COUNT(*) AS row_count
FROM users
WHERE id = '${SYSTEM_USER_ID}'

UNION ALL

SELECT
	'wiki_pages',
	COUNT(*)
FROM wiki_pages

UNION ALL

SELECT
	'wiki_revisions',
	COUNT(*)
FROM wiki_revisions

UNION ALL

SELECT
	'published_pages',
	COUNT(*)
FROM wiki_pages
WHERE published_revision_id IS NOT NULL;`,
	);

	lines.push('');

	return lines.join('\n');
}


/* =========================================================
   Main
   ========================================================= */

function main() {
	if (!fs.existsSync(docsRoot)) {
		throw new Error(
			`Wiki directory が見つかりません:\n${docsRoot}`,
		);
	}

	const files =
		collectFiles(docsRoot).sort();

	console.log('');
	console.log(
		'========================================',
	);

	console.log(
		'NUGBASE Production Wiki Initializer',
	);

	console.log(
		'========================================',
	);

	console.log('');

	console.log(
		`対象ディレクトリ: ${docsRoot}`,
	);

	console.log(
		`検出ファイル数: ${files.length}`,
	);

	console.log('');


	const pages = [];
	const errors = [];

	for (const filePath of files) {
		try {
			const content =
				fs.readFileSync(
					filePath,
					'utf8',
				);

			const title =
				getTitle(
					content,
					filePath,
				);

			const sourcePath =
				getSourcePath(
					filePath,
				);

			const publicPath =
				getPublicPath(
					filePath,
				);

			pages.push({
				title,
				path: publicPath,
				sourcePath,
				content,
			});
		} catch (error) {
			errors.push({
				filePath,
				message:
					error instanceof Error
						? error.message
						: String(error),
			});
		}
	}


	/* =====================================================
	   Results
	   ===================================================== */

	for (const page of pages) {
		console.log(
			`[OK] ${page.path}`,
		);

		console.log(
			`     title: ${page.title}`,
		);

		console.log(
			`     source: ${page.sourcePath}`,
		);

		console.log(
			`     content: ${page.content.length} characters`,
		);

		console.log('');
	}


	if (errors.length > 0) {
		console.log(
			'========================================',
		);

		console.log(
			'ERROR',
		);

		console.log(
			'========================================',
		);

		console.log('');

		for (const error of errors) {
			console.log(
				`[ERROR] ${error.filePath}`,
			);

			console.log(
				`        ${error.message}`,
			);

			console.log('');
		}

		process.exitCode = 1;

		return;
	}


	console.log(
		'========================================',
	);

	console.log(
		'検証結果',
	);

	console.log(
		'========================================',
	);

	console.log(
		`検出: ${files.length} ファイル`,
	);

	console.log(
		`成功: ${pages.length} ファイル`,
	);

	console.log(
		`エラー: ${errors.length} ファイル`,
	);

	console.log('');


	if (pages.length !== EXPECTED_PAGE_COUNT) {
		console.log(
			`WARNING: Wikiページ数が${EXPECTED_PAGE_COUNT}ではありません: ${pages.length}`,
		);

		console.log(
			'現在のソース状態を確認してからSQLを生成してください。',
		);

		console.log('');
	}


	fs.mkdirSync(
		generatedDirectory,
		{
			recursive: true,
		},
	);

	const sql =
		createSql(pages);

	fs.writeFileSync(
		outputFile,
		sql,
		'utf8',
	);

	console.log(
		'========================================',
	);

	console.log(
		'SQL生成完了',
	);

	console.log(
		'========================================',
	);

	console.log('');

	console.log(
		`SQL: ${outputFile}`,
	);

	console.log('');

	console.log(
		`Wiki pages: ${pages.length}`,
	);

	console.log(
		'System user: NUGBASE (admin)',
	);

	console.log(
		'Initial revisions: Revision 1',
	);

	console.log('');

	console.log(
		'この時点ではD1への書き込みは行っていません。',
	);

	console.log('');
}


main();