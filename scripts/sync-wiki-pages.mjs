import fs from 'node:fs';
import path from 'node:path';

const projectRoot = process.cwd();
const docsRoot = path.join(projectRoot, 'src', 'content', 'docs', 'docs');
const outputDirectory = path.join(projectRoot, 'scripts', 'generated');
const outputFile = path.join(outputDirectory, 'sync-wiki-pages.sql');

const SUPPORTED_EXTENSIONS = new Set(['.md', '.mdx']);

/**
 * Markdown / MDX の frontmatter から title を取得する。
 */
function getTitle(content, filePath) {
	const match = content.match(/^---\s*\n([\s\S]*?)\n---\s*(?:\n|$)/);

	if (!match) {
		throw new Error(`frontmatter がありません: ${filePath}`);
	}

	const frontmatter = match[1];

	const titleMatch = frontmatter.match(
		/^title\s*:\s*(?:"([^"]*)"|'([^']*)'|(.+))\s*$/m
	);

	if (!titleMatch) {
		throw new Error(`title がありません: ${filePath}`);
	}

	return (titleMatch[1] ?? titleMatch[2] ?? titleMatch[3]).trim();
}

/**
 * ディレクトリを再帰的に走査して Markdown / MDX を取得する。
 */
function collectFiles(directory) {
	const results = [];

	for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
		const fullPath = path.join(directory, entry.name);

		if (entry.isDirectory()) {
			results.push(...collectFiles(fullPath));
			continue;
		}

		if (!entry.isFile()) {
			continue;
		}

		if (!SUPPORTED_EXTENSIONS.has(path.extname(entry.name).toLowerCase())) {
			continue;
		}

		results.push(fullPath);
	}

	return results;
}

/**
 * source file から Starlight の公開URLを作る。
 *
 * 例:
 * src/content/docs/docs/index.mdx
 *   -> /docs/
 *
 * src/content/docs/docs/plugins/lands/index.md
 *   -> /docs/plugins/lands/
 *
 * src/content/docs/docs/plugins/lands/upkeep.md
 *   -> /docs/plugins/lands/upkeep/
 */
function getPublicPath(filePath) {
	const relative = path.relative(docsRoot, filePath);
	const parsed = path.parse(relative);

	let urlPath;

	if (parsed.name === 'index') {
		const directory = parsed.dir.replaceAll(path.sep, '/');

		urlPath = directory
			? `/docs/${directory}/`
			: '/docs/';
	} else {
		const directory = parsed.dir.replaceAll(path.sep, '/');

		urlPath = directory
			? `/docs/${directory}/${parsed.name}/`
			: `/docs/${parsed.name}/`;
	}

	return urlPath.replace(/\/+/g, '/');
}

/**
 * Windowsのパス区切りを / に統一した
 * プロジェクト相対パスを作る。
 */
function getSourcePath(filePath) {
	return path
		.relative(projectRoot, filePath)
		.split(path.sep)
		.join('/');
}

/**
 * SQL文字列用のエスケープ。
 *
 * SQLiteではシングルクォートを2つにする。
 */
function escapeSql(value) {
	return value.replaceAll("'", "''");
}

/**
 * D1用のINSERT ... ON CONFLICT SQLを生成する。
 *
 * source_path が既存の場合:
 * - path
 * - title
 * - updated_at
 *
 * を更新する。
 *
 * 以下は変更しない:
 * - id
 * - published_revision_id
 * - created_at
 */
function createSql(pages) {
	const timestamp = new Date().toISOString();

	const lines = [];

	lines.push('-- ========================================================');
	lines.push('-- NUGBASE Wiki pages synchronization');
	lines.push('-- Generated by scripts/sync-wiki-pages.mjs');
	lines.push('-- ========================================================');
	lines.push(`-- Generated at: ${timestamp}`);
	lines.push(`-- Pages: ${pages.length}`);
	lines.push('--');
	lines.push('-- This SQL only updates wiki_pages.');
	lines.push('-- It does NOT create wiki_revisions or edit_requests.');
	lines.push('-- Existing rows that are not present in the source are NOT deleted.');
	lines.push('-- ========================================================');
	lines.push('');
	lines.push('BEGIN TRANSACTION;');
	lines.push('');

	for (const page of pages) {
		const id = crypto.randomUUID();
		const title = escapeSql(page.title);
		const publicPath = escapeSql(page.path);
		const sourcePath = escapeSql(page.sourcePath);

		lines.push(`-- ${page.path}`);
		lines.push(
			`INSERT INTO wiki_pages (id, path, title, source_path, published_revision_id, created_at, updated_at)`
		);
		lines.push(
			`VALUES ('${id}', '${publicPath}', '${title}', '${sourcePath}', NULL, '${timestamp}', '${timestamp}')`
		);
		lines.push(
			`ON CONFLICT(source_path) DO UPDATE SET`
		);
		lines.push(
			`  path = excluded.path,`
		);
		lines.push(
			`  title = excluded.title,`
		);
		lines.push(
			`  updated_at = excluded.updated_at;`
		);
		lines.push('');
	}

	lines.push('COMMIT;');
	lines.push('');

	return lines.join('\n');
}

function main() {
	const generateSql = process.argv.includes('--generate-sql');

	if (!fs.existsSync(docsRoot)) {
		throw new Error(`Wikiディレクトリが見つかりません:\n${docsRoot}`);
	}

	const files = collectFiles(docsRoot).sort();

	console.log('');
	console.log('========================================');
	console.log('NUGBASE Wiki 同期 dry-run');
	console.log('========================================');
	console.log('');
	console.log(`対象ディレクトリ: ${docsRoot}`);
	console.log(`検出ファイル数: ${files.length}`);
	console.log('');

	const pages = [];
	const errors = [];

	for (const filePath of files) {
		try {
			const content = fs.readFileSync(filePath, 'utf8');
			const title = getTitle(content, filePath);
			const sourcePath = getSourcePath(filePath);
			const publicPath = getPublicPath(filePath);

			pages.push({
				title,
				path: publicPath,
				sourcePath,
			});
		} catch (error) {
			errors.push({
				filePath,
				message: error instanceof Error ? error.message : String(error),
			});
		}
	}

	for (const page of pages) {
		console.log(`[OK] ${page.path}`);
		console.log(`     title: ${page.title}`);
		console.log(`     source: ${page.sourcePath}`);
		console.log('');
	}

	if (errors.length > 0) {
		console.log('========================================');
		console.log('エラー');
		console.log('========================================');
		console.log('');

		for (const error of errors) {
			console.log(`[ERROR] ${error.filePath}`);
			console.log(`        ${error.message}`);
			console.log('');
		}
	}

	console.log('========================================');
	console.log('結果');
	console.log('========================================');
	console.log(`検出: ${files.length} ファイル`);
	console.log(`成功: ${pages.length} ファイル`);
	console.log(`エラー: ${errors.length} ファイル`);
	console.log('');

	if (errors.length > 0) {
		console.log('✗ エラーがあるため、SQLは生成しません。');
		console.log('');
		process.exitCode = 1;
		return;
	}

	console.log('✓ すべてのWikiページを正常に認識できました。');

	if (!generateSql) {
		console.log('✓ SQL生成モードではないため、SQLファイルは作成しません。');
		console.log('');
		return;
	}

	fs.mkdirSync(outputDirectory, { recursive: true });

	const sql = createSql(pages);

	fs.writeFileSync(outputFile, sql, 'utf8');

	console.log('');
	console.log('========================================');
	console.log('SQL生成');
	console.log('========================================');
	console.log('');
	console.log(`✓ SQLファイルを生成しました。`);
	console.log(`  ${outputFile}`);
	console.log('');
	console.log(`✓ ${pages.length}ページ分のSQLを生成しました。`);
	console.log('✓ D1への書き込みはまだ行っていません。');
	console.log('');
}

main();